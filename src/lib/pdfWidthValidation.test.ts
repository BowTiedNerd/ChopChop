import { pdfShownText } from './pdfTestText';
/**
 * PDF Text Validation for Wide Panels
 * Ensures flatten step text is panel-specific and contains no generic "planer is allowed" text
 */

import { describe, it, expect } from 'vitest';
import { PdfGenerator } from './pdf';
import { BoardDesign, BoardStyle } from '../types';
import { calculateRequiredParts } from './lumberPlanner';
import { loadStyleCatalog } from './catalogLoader';
import { CatalogStyleName } from '../types/catalog';
import { readFileSync } from 'fs';

const PANEL_MAX_WIDTH_MM = 305;

/**
 * Extract flatten step text from PDF binary
 * PDFs generated by jsPDF have spaces between individual characters
 */
function extractFlattenStepText(pdfBuffer: Buffer): string {
  const pdfText = pdfBuffer.toString('latin1');
  
  // Find "Flatten first panel" step
  const stepIdx = pdfText.indexOf('Flatten first panel');
  if (stepIdx === -1) return '';
  
  // Extract ~2000 chars after the step title to get the description
  const textAfterTitle = pdfText.substring(stepIdx, stepIdx + 2000);
  
  // Remove PDF formatting commands and extract just the text content
  // Look for text between parentheses which contain the actual content
  const textMatches = textAfterTitle.match(/\([^)]+\)\s*Tj/g);
  if (!textMatches) return '';
  
  // Extract content from parentheses and join
  const extractedText = textMatches
    .map(match => {
      const content = match.match(/\(([^)]+)\)/);
      return content ? content[1] : '';
    })
    .join(' ');
  
  return extractedText;
}

/**
 * Create a board design with many species to force wide panels
 */
function createWidePanelDesign(style: string, width: number, speciesCount: number): BoardDesign {
  const species = [
    { name: 'Walnut', color: '#654321' },
    { name: 'Maple', color: '#F5E6D3' },
    { name: 'Cherry', color: '#C04000' },
    { name: 'Oak', color: '#D2B48C' },
    { name: 'Ash', color: '#E8D7C3' },
    { name: 'Mahogany', color: '#C04000' },
    { name: 'Birch', color: '#F3E5D8' },
    { name: 'Beech', color: '#F5DEB3' },
    { name: 'Hickory', color: '#E5C9A3' },
    { name: 'Teak', color: '#8B7355' },
    { name: 'Cedar', color: '#A68B6B' },
    { name: 'Pine', color: '#E9C2A6' },
  ].slice(0, speciesCount);
  
  return {
    style: style as BoardStyle,
    dimensions: { width, length: 450, thickness: 38 },
    species,
    angle: style === 'chevron' || style === 'herringbone' ? 45 : undefined,
    juiceGroove: { enabled: false, width: 0, depth: 0, fromEdge: 0, cornerRadius: 0 },
    handles: { enabled: false, type: 'handle' },
    rubberFeet: { enabled: false, diameter: 0, height: 0, inset: 0 },
    unitSystem: 'imperial',
  };
}

describe('PDF Flatten Step Text for Wide Panels (N7)', () => {
  it('should have panel-specific flatten text in PDF, not generic "planer is allowed"', () => {
    const violations: string[] = [];
    
    // Test configuration that produces wide panels
    // Checkerboard with 10 species produces 454mm panel
    const testCases = [
      { style: 'checkerboard', width: 500, speciesCount: 10, expectedPanelWidth: 454 },
    ];
    
    for (const testCase of testCases) {
      const catalog = loadStyleCatalog(testCase.style as CatalogStyleName);
      
      // Skip if not a strip-set panel style
      if (!catalog.cutListAllowances.blankRule?.blankUnit || 
          catalog.cutListAllowances.blankRule.blankUnit !== 'stripSetPanel') {
        continue;
      }
      
      // Create design and generate PDF
      const design = createWidePanelDesign(testCase.style, testCase.width, testCase.speciesCount);
      const cutList = calculateRequiredParts(design);
      
      const panels = cutList.filter(item => item.part.includes('strip-set panel'));
      // No panel wider than the planer max may be planed
      for (const p of panels) {
        if (p.width > PANEL_MAX_WIDTH_MM && !/router sled/.test(p.part)) {
          violations.push(`${testCase.style}: ${p.width.toFixed(0)}mm panel not split and not on router sled`);
        }
        if (p.width > PANEL_MAX_WIDTH_MM && /plane flat/.test(p.part)) {
          violations.push(`${testCase.style}: ${p.width.toFixed(0)}mm panel has a planer step`);
        }
      }
      const generator = new PdfGenerator(design);
      const pdf = generator.generateCutSheet(cutList);
      const raw = Buffer.from(pdf.output('arraybuffer')).toString('latin1');
      const shown = pdfShownText(raw);
      const lines = shown.match(/Flatten panel \d+\/\d+/g) ?? [];
      if (lines.length !== panels.length) {
        violations.push(`${testCase.style}: ${lines.length} flatten lines for ${panels.length} panels`);
      }
      if (/planer is allowed/i.test(shown)) violations.push(`${testCase.style}: generic "planer is allowed"`);
    }

    if (violations.length > 0) {
      throw new Error(
        `PDF flatten step text violations:\n  - ${violations.join('\n  - ')}\n\n` +
        `Wide panels must have panel-specific text with width and routing method, not generic "planer is allowed".`
      );
    }
    
    expect(violations.length).toBe(0);
  });

  it('should validate all sample PDFs with wide panels', () => {
    const violations: string[] = [];
    
    // Check committed sample PDFs
    const sampleFiles = [
      'samples/checkerboard-16x24.pdf',
      'samples/checkerboard-default.pdf',
      'samples/chevron.pdf',
    ];
    
    for (const filePath of sampleFiles) {
      const pdfBuffer = readFileSync(filePath); // a missing sample is a failure
      
      const flattenText = extractFlattenStepText(pdfBuffer);
      
      // Check if this sample has "planer is allowed" (shouldn't for any wide panel)
      if (flattenText.toLowerCase().includes('planer is allowed')) {
        // This might be OK if the sample has narrow panels only
        // But if it mentions a width > 305mm, it's a violation
        const wideWidthPattern = /(\d+)\s*mm/g;
        let match;
        while ((match = wideWidthPattern.exec(flattenText)) !== null) {
          const width = parseInt(match[1], 10);
          if (width > PANEL_MAX_WIDTH_MM) {
            violations.push(
              `${filePath}: Contains "planer is allowed" text with ${width}mm panel width`
            );
            break;
          }
        }
      }
    }
    
    if (violations.length > 0) {
      throw new Error(
        `Sample PDF violations:\n  - ${violations.join('\n  - ')}`
      );
    }
    
    expect(violations.length).toBe(0);
  });
});
